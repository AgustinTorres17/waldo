import AppKit

/// Saves, restores and writes the general pasteboard (RESEARCH §4.3, §4.6).
@MainActor
enum ClipboardService {
    /// A deep copy of the pasteboard's items, taken before we touch it.
    struct Snapshot {
        fileprivate let items: [NSPasteboardItem]
    }

    private static var pasteboard: NSPasteboard { .general }

    /// Larger payloads (images, files) are skipped rather than copied into memory.
    private static let maxBytesPerType = 50 * 1024 * 1024
    /// File promises can't be cloned faithfully; skip them.
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("com.apple.NSFilePromiseItemMetaData"),
        NSPasteboard.PasteboardType("com.apple.pasteboard.promised-file-url"),
    ]

    // nspasteboard.org markers, so clipboard managers ignore our temporary content.
    private static let transientTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]
    private static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")

    static var changeCount: Int { pasteboard.changeCount }

    static func snapshot() -> Snapshot {
        let items = (pasteboard.pasteboardItems ?? []).compactMap { item -> NSPasteboardItem? in
            let copy = NSPasteboardItem()
            // Copy the type list first: the pasteboard may change while we iterate.
            for type in Array(item.types) where !skippedTypes.contains(type) {
                if let data = item.data(forType: type), data.count <= maxBytesPerType {
                    copy.setData(data, forType: type)
                }
            }
            return copy.types.isEmpty ? nil : copy
        }
        return Snapshot(items: items)
    }

    static func restore(_ snapshot: Snapshot) {
        pasteboard.clearContents()
        if !snapshot.items.isEmpty {
            pasteboard.writeObjects(snapshot.items)
        }
    }

    static func readString() -> String? {
        pasteboard.string(forType: .string)
    }

    /// Writes plain text marked as transient; returns the resulting change count.
    @discardableResult
    static func writeTransient(_ text: String) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in transientTypes { item.setString("", forType: type) }
        item.setString(Bundle.main.bundleIdentifier ?? "Waldo", forType: sourceType)
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// Writes plain text the user is meant to keep (no transient markers).
    static func writeString(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    /// Polls changeCount until it moves past `baseline` (RESEARCH §4.3).
    /// Only runs for ≤ timeout right after we post ⌘C.
    static func waitForChange(from baseline: Int, timeout: Duration = .milliseconds(500)) async -> Bool {
        try? await Task.sleep(for: .milliseconds(50))
        let deadline = ContinuousClock.now + timeout
        while ContinuousClock.now < deadline {
            if pasteboard.changeCount != baseline { return true }
            try? await Task.sleep(for: .milliseconds(5))
        }
        return pasteboard.changeCount != baseline
    }
}
